export function caseBySlug(slug: string): CaseEntry | undefined {
  return CASES.find((c) => c.slug === slug);
}

export function casesByCategory(category: string): CaseEntry[] {
  return CASES.filter((c) => c.category === category);
}

export function casesByTag(tag: string): CaseEntry[] {
  return CASES.filter((c) => c.tag === tag);
}

/** Cases the upstream list has run its REA claim check against. */
export function verifiedCases(): CaseEntry[] {
  return CASES.filter((c) => c.verification);
}

/** Cases with a known repo creation date, newest first. */
export function newestCases(): CaseEntry[] {
  return CASES.filter((c) => c.created).sort((a, b) =>
    (b.created ?? "").localeCompare(a.created ?? ""),
  );
}

/** Every "replaces or works with" pairing, for the by-app index. */
export function byAppIndex(): { app: string; entry: CaseEntry }[] {
  return CASES.flatMap((entry) =>
    (entry.replaces ?? []).map((app) => ({ app, entry })),
  ).sort((a, b) => a.app.localeCompare(b.app));
}

export function tagCounts(): { tag: CaseEntry["tag"]; count: number }[] {
  const counts = new Map<CaseEntry["tag"], number>();
  for (const c of CASES) counts.set(c.tag, (counts.get(c.tag) ?? 0) + 1);
  return [...counts.entries()]
    .map(([tag, count]) => ({ tag, count }))
    .sort((a, b) => b.count - a.count);
}
