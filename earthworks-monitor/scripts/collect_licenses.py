#!/usr/bin/env python3
"""Collect the licence texts of every dependency shipped in the images.

Run from the repository's earthworks-monitor/ directory after installing dependencies:

    backend/.venv/bin/python scripts/collect_licenses.py

It reads the installed Python distributions named in backend/requirements.lock and the
production npm packages under frontend/node_modules, writes one text file per package
under LICENSES/, and regenerates THIRD_PARTY.md. Re-run it whenever dependencies change.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "LICENSES"
LICENSE_FILE = re.compile(r"(^|/)(LICEN[CS]E|COPYING|NOTICE|AUTHORS)[^/]*$", re.IGNORECASE)


def safe(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", name)


def python_packages() -> list[dict]:
    rows = []
    target = OUT / "python"
    for line in (ROOT / "backend" / "requirements.lock").read_text().splitlines():
        if "==" not in line:
            continue
        name = line.split("==")[0].strip()
        dist = metadata.distribution(name)
        meta = dist.metadata
        licence = meta.get("License-Expression") or ""
        if not licence:
            classifiers = [
                c.split("::")[-1].strip() for c in meta.get_all("Classifier", []) if c.startswith("License")
            ]
            first_line = (meta.get("License") or "").strip().splitlines()[:1]
            licence = "; ".join(classifiers) or (first_line[0][:80] if first_line else "see licence file")
        texts = []
        for file in dist.files or []:
            if LICENSE_FILE.search(str(file)) and ".dist-info" in str(file):
                path = Path(dist.locate_file(file))
                if path.is_file():
                    texts.append(f"===== {file.name} =====\n{path.read_text(errors='replace')}")
        home = meta.get("Home-page") or next((u.split(",", 1)[1].strip() for u in meta.get_all("Project-URL", []) if "," in u), "")
        body = "\n\n".join(texts) or f"No licence file is included in the installed distribution.\nDeclared licence: {licence}\nProject: {home}\n"
        filename = f"{safe(meta['Name'])}-{dist.version}.txt"
        (target / filename).write_text(body)
        rows.append({"name": meta["Name"], "version": dist.version, "licence": licence, "file": f"LICENSES/python/{filename}"})
    return sorted(rows, key=lambda r: r["name"].lower())


def javascript_packages() -> list[dict]:
    frontend = ROOT / "frontend"
    listing = subprocess.run(
        ["npm", "ls", "--omit=dev", "--all", "--parseable"], cwd=frontend, capture_output=True, text=True
    ).stdout.splitlines()
    rows, seen = [], set()
    target = OUT / "javascript"
    for directory in map(Path, listing[1:]):
        manifest = directory / "package.json"
        if not manifest.is_file():
            continue
        package = json.loads(manifest.read_text())
        key = (package["name"], package["version"])
        if key in seen:
            continue
        seen.add(key)
        licence = package.get("license") or "see licence file"
        if isinstance(licence, dict):
            licence = licence.get("type", "see licence file")
        texts = [
            f"===== {path.name} =====\n{path.read_text(errors='replace')}"
            for path in sorted(directory.iterdir())
            if path.is_file() and LICENSE_FILE.search(path.name)
        ]
        body = "\n\n".join(texts) or f"No licence file is included in the package.\nDeclared licence: {licence}\nPackage: https://www.npmjs.com/package/{package['name']}\n"
        filename = f"{safe(package['name'])}-{package['version']}.txt"
        (target / filename).write_text(body)
        rows.append({"name": package["name"], "version": package["version"], "licence": licence, "file": f"LICENSES/javascript/{filename}"})
    return sorted(rows, key=lambda r: r["name"].lower())


def table(rows: list[dict]) -> str:
    lines = ["| Package | Version | Licence | Text |", "|---|---|---|---|"]
    lines += [f"| {r['name']} | {r['version']} | {r['licence']} | [{Path(r['file']).name}]({r['file']}) |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    for sub in ("python", "javascript", "fonts"):
        shutil.rmtree(OUT / sub, ignore_errors=True)
        (OUT / sub).mkdir(parents=True)
    shutil.copyfile(ROOT / "backend/app/reports/fonts/OFL.txt", OUT / "fonts" / "Noto-fonts-OFL-1.1.txt")
    python_rows, js_rows = python_packages(), javascript_packages()
    (ROOT / "THIRD_PARTY.md").write_text(
        f"""# Third-party software

Generated by `scripts/collect_licenses.py`; do not edit by hand. Attribution for NASA Ames
Stereo Pipeline and the demonstration data is in [NOTICE.md](NOTICE.md).

## Installed alongside the application

| Component | Version | Licence | Text |
|---|---|---|---|
| NASA Ames Stereo Pipeline (worker image) | 3.7.0 | Apache-2.0 | [NASA-Ames-Stereo-Pipeline-Apache-2.0.txt](LICENSES/NASA-Ames-Stereo-Pipeline-Apache-2.0.txt) |
| Noto Sans and Noto Sans Arabic fonts (PDF report, web UI) | – | SIL Open Font License 1.1 | [Noto-fonts-OFL-1.1.txt](LICENSES/fonts/Noto-fonts-OFL-1.1.txt) |

Ames Stereo Pipeline bundles further libraries (ISIS, GDAL, PROJ, PDAL, OpenCV and
others) under their own licences, listed in its documentation under "Third party
licenses". The container base images (Debian with Python, PostgreSQL with PostGIS, Redis,
nginx) are pulled from their publishers and are not redistributed in this repository.

## Python packages ({len(python_rows)}) — api, worker and tiler images

{table(python_rows)}

## JavaScript packages ({len(js_rows)}) — compiled into the web client

{table(js_rows)}
"""
    )
    print(f"{len(python_rows)} Python and {len(js_rows)} JavaScript packages -> {OUT}")


if __name__ == "__main__":
    main()
